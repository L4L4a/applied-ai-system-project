"""
Agentic trace: write the pipeline's intermediate steps (validate -> parse -> retrieve -> rank ->
self-check -> explain) to a markdown file.

  python -m src.trace                      # regenerate the trace section of ai_interactions.md
  python -m src.main --query "..." --trace out.md
The section lives between two HTML comment markers, so re-running replaces it instead of appending.
"""

import json
from typing import Any, List, Tuple

from src.pipeline import Pipeline, PipelineResult

START = "<!-- AGENTIC-TRACE:START -->"
END = "<!-- AGENTIC-TRACE:END -->"
DEFAULT_REQUESTS = [
    "late night study session, something mellow",
    {"genre": "jazz", "mood": "relaxed", "energy": 0.3},
    {"genre": "zydeco", "mood": "happy"},
]


def format_trace(raw: Any, result: PipelineResult, index: int = 1) -> str:
    lines = [f"### Trace {index}: `{raw!r}`", ""]
    for n, step in enumerate(result.steps, start=1):
        detail = {k: v for k, v in step.items() if k != "step"}
        lines += [f"**Step {n}: {step['step']}**", "", "```json", json.dumps(detail, indent=2, default=str), "```", ""]
    if result.ok:
        lines.append(f"**Outcome:** OK, mode `{result.mode}`, overall confidence {result.confidence:.2f}. Final top 3:")
        lines.append("")
        for rec in result.recommendations[:3]:
            lines.append(f"- {rec.song['title']} (confidence {rec.confidence:.2f}): {rec.explanation}")
    else:
        lines.append(f"**Outcome:** REJECTED at the last recorded step with message: {result.error}")
    return "\n".join(lines) + "\n"


def save_traces(path: str, items: List[Tuple[Any, PipelineResult]]) -> None:
    body = "\n".join(format_trace(raw, res, i) for i, (raw, res) in enumerate(items, start=1))
    section = (f"{START}\n## Agentic Pipeline Trace\n\n"
               "Generated by `python -m src.trace`. Each request goes through the same six steps; the JSON "
               "under each step is the data that step handed to the next one.\n\n" + body + f"\n{END}\n")
    try:
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    except FileNotFoundError:
        existing = ""
    if START in existing and END in existing:
        head, _, rest = existing.partition(START)
        _, _, tail = rest.partition(END)
        new = head + section.rstrip("\n") + tail
    else:
        new = existing.rstrip("\n") + ("\n\n" if existing else "") + section
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)


def save_trace(path: str, raw: Any, result: PipelineResult) -> None:
    save_traces(path, [(raw, result)])


def main() -> None:
    pipeline = Pipeline()
    items = [(raw, pipeline.run(raw)) for raw in DEFAULT_REQUESTS]
    save_traces("ai_interactions.md", items)
    print(f"Saved {len(items)} traces to ai_interactions.md")


if __name__ == "__main__":
    main()
